import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const modules = JSON.parse(readFileSync(new URL('./bindings.json', import.meta.url), 'utf8'));
for (const [name, exports] of Object.entries(modules)) {
  const path = resolve(root, 'apps/studio', name);
  const groups = new Map();
  for (const [publicName, binding] of Object.entries(exports)) {
    const declaration = readFileSync(resolve(dirname(path), binding.module.replace(/\.js$/, '.d.ts')), 'utf8');
    if (!new RegExp(`export (?:declare )?(?:function|const|class) ${binding.name}\\b`).test(declaration)) {
      throw new Error(`${name}: MoonBit no longer exports ${binding.name}`);
    }
    const group = groups.get(binding.module) ?? [];
    group.push(binding.name === publicName ? publicName : `${binding.name} as ${publicName}`);
    groups.set(binding.module, group);
  }
  const source = '// Generated by scripts/generate-bindings.mjs; edit scripts/bindings.json and the adjacent public declaration.\n'
    + [...groups].map(([module, names]) => `export { ${names.join(', ')} } from ${JSON.stringify(module)};`).join('\n') + '\n';
  writeFileSync(path, source);
}
